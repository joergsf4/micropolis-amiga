#!/usr/bin/env python3
"""Translation catalogs for Micropolis (Amiga locale.library, FlexCat formats).

The program asks the catalog for T("English text"); the catalog id of a text is the 31 bit FNV-1a hash of the English
text (src/amiga/l10n.c does the same), so there is no id table in the code. Texts come from

  - the sources: T("...") and N_("...") in src/amiga/*.c
  - the original resources: res/stri.* lines (status messages, query words), out/data/notices.txt (titles and stories)
  - tools/l10n/extra.txt: strings that come from the simulation core (city classes, levels, problems, months)

usage:
  l10n.py extract       writes l10n/Micropolis.cd and brings every l10n/<language>.ct up to date
                        (new texts are added with the English text, removed texts are dropped, translations are kept)
  l10n.py check         lists, per language, the texts that are still English, and hash collisions

Translators work on l10n/<language>.ct (plain text, keep the %s %d %ld codes and the \\n escapes), then
`make catalogs` (or ./build.sh) turns them into Catalogs/<language>/Micropolis.catalog with FlexCat.
"""
import glob
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
L10N = os.path.join(ROOT, 'l10n')


def fnv(text):
    h = 2166136261
    for b in text.encode('latin-1'):
        h = ((h ^ b) * 16777619) & 0xffffffff
    return h & 0x7fffffff


def c_unescape(lit):
    out = bytearray()
    i = 0
    simple = {'n': 10, 't': 9, 'r': 13, '\\': 92, '"': 34, "'": 39, '0': 0}
    while i < len(lit):
        c = lit[i]
        if c == '\\':
            i += 1
            c = lit[i]
            if c in simple and c != '0':
                out.append(simple[c])
            elif c == 'x':
                out.append(int(lit[i + 1:i + 3], 16)); i += 2
            else:
                out.append(ord(c))
        else:
            out.append(ord(c))
        i += 1
    return out.decode('latin-1')


def source_strings():
    pat = re.compile(r'\b(?:T|N_)\(\s*((?:"(?:[^"\\]|\\.)*"\s*)+)\)')
    found = []
    for path in sorted(glob.glob(os.path.join(ROOT, 'src', 'amiga', '*.c'))):
        txt = open(path, encoding='latin-1').read()
        for m in pat.finditer(txt):
            parts = re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(1))
            found.append(c_unescape(''.join(parts)))
    return found


def resource_strings():
    out = []
    for path in sorted(glob.glob(os.path.join(ROOT, 'upstream', 'res', 'stri.*'))):
        for line in open(path, encoding='latin-1').read().split('\n'):
            if line.strip():
                out.append(line)
    notices = os.path.join(ROOT, 'out', 'data', 'notices.txt')
    if os.path.exists(notices):
        for line in open(notices, encoding='latin-1').read().split('\n'):
            parts = line.split('|')
            if len(parts) >= 3:
                out.append(parts[1])
                out.append('|'.join(parts[2:]))
    extra = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'extra.txt')
    for line in open(extra, encoding='latin-1').read().split('\n'):
        if line and not line.startswith('#'):
            out.append(line)
    return out


def all_strings():
    seen, order = set(), []
    for s in source_strings() + resource_strings():
        if s not in seen:
            seen.add(s)
            order.append(s)
    return order


def esc(s):
    return s.replace('\\', '\\\\').replace('\n', '\\n').replace('\t', '\\t')


def unesc(s):
    out, i = [], 0
    while i < len(s):
        if s[i] == '\\' and i + 1 < len(s):
            i += 1
            out.append({'n': '\n', 't': '\t', '\\': '\\'}.get(s[i], '\\' + s[i]))
        else:
            out.append(s[i])
        i += 1
    return ''.join(out)


def name(s):
    return 'S_%08X' % fnv(s)


def write_cd(strings):
    os.makedirs(L10N, exist_ok=True)
    lines = ['#version 1', '#language english', ';',
             '; Catalog description for Micropolis. Generated by tools/l10n/l10n.py - do not edit by hand.', ';']
    for s in strings:
        lines.append('%s (%d//)' % (name(s), fnv(s)))
        lines.append(esc(s))
    open(os.path.join(L10N, 'Micropolis.cd'), 'w', encoding='latin-1', newline='\n').write('\n'.join(lines) + '\n')


def read_ct(path):
    tr, lang = {}, None
    lines = open(path, encoding='latin-1').read().split('\n')
    i = 0
    while i < len(lines):
        ln = lines[i]
        if ln.startswith('## language'):
            lang = ln.split(None, 2)[2].strip()
        if re.match(r'^S_[0-9A-F]{8}$', ln) and i + 1 < len(lines):
            tr[ln] = unesc(lines[i + 1])
            i += 1
        i += 1
    return lang, tr


def write_ct(path, lang, strings, tr):
    lines = ['## version $VER: Micropolis.catalog 1.0 (15.10.2026)', '## codeset 0', '## language %s' % lang, ';',
             '; Translation for Micropolis. Keep the %s %d %ld codes and the \\n escapes; the comment lines show the English text.', ';']
    for s in strings:
        lines.append(name(s))
        lines.append(esc(tr.get(name(s), s)))
        lines.append('; ' + esc(s))
    open(path, 'w', encoding='latin-1', newline='\n').write('\n'.join(lines) + '\n')


def extract():
    strings = all_strings()
    names = {}
    for s in strings:
        n = name(s)
        if n in names and names[n] != s:
            sys.exit('hash collision: %r / %r' % (names[n], s))
        names[n] = s
    write_cd(strings)
    for path in sorted(glob.glob(os.path.join(L10N, '*.ct'))):
        lang, tr = read_ct(path)
        write_ct(path, lang, strings, tr)
        print('%s: %d texts' % (os.path.basename(path), len(strings)))
    print('Micropolis.cd: %d texts' % len(strings))


def check():
    strings = all_strings()
    for path in sorted(glob.glob(os.path.join(L10N, '*.ct'))):
        lang, tr = read_ct(path)
        missing = [s for s in strings if tr.get(name(s), s) == s and re.search('[A-Za-z]{3}', s)]
        print('%s (%s): %d of %d texts equal to English' % (os.path.basename(path), lang, len(missing), len(strings)))
        if '-v' in sys.argv:
            for s in missing:
                print('   ', esc(s)[:100])


if __name__ == '__main__':
    cmd = sys.argv[1] if len(sys.argv) > 1 else ''
    if cmd == 'extract':
        extract()
    elif cmd == 'check':
        check()
    else:
        print(__doc__)
